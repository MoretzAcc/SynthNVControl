class DeviceDialog(QDialog):
    def __init__(self):
        super().__init__()

        self.setWindowTitle("Select Serial Device")
        self.resize(800, 350)

        self.selected_port = None

        layout = QVBoxLayout(self)

        self.devices = QListWidget()
        self.devices.setTextElideMode(Qt.TextElideMode.ElideRight)
        self.devices.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        layout.addWidget(self.devices)

        buttons = QHBoxLayout()

        refresh = QPushButton("Refresh")
        self.ok = QPushButton("OK")
        self.ok.setEnabled(False)

        buttons.addWidget(refresh)
        buttons.addStretch()
        buttons.addWidget(self.ok)

        layout.addLayout(buttons)

        refresh.clicked.connect(self.refresh)
        self.ok.clicked.connect(self.accept_device)
        self.devices.itemSelectionChanged.connect(
            lambda: self.ok.setEnabled(bool(self.devices.selectedItems()))
        )
        self.devices.itemDoubleClicked.connect(
            lambda _: self.accept_device()
        )

        self.refresh()

    def refresh(self):
        self.devices.clear()

        for port in list_ports.comports():
            if port.vid is None:
                continue

            name = port.product or port.description or "USB Serial Device"
            manufacturer = port.manufacturer or ""
            vidpid = f"{port.vid:04X}:{port.pid:04X}"

            item_text = (
                f"{name}\n"
                f"    Port: {port.device}    Name: {port.name}    [{vidpid}]\n"
                f"    Manufacturer: {manufacturer}"
            )
            self.devices.addItem(item_text)
            self.devices.item(self.devices.count() - 1).setData(
                Qt.ItemDataRole.UserRole,
                port.device
            )

        self.ok.setEnabled(False)

    def accept_device(self):
        item = self.devices.currentItem()

        if item is None:
            return

        self.selected_port = item.data(Qt.ItemDataRole.UserRole)
        self.accept()


